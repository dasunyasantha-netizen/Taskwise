// Generates src/styles/palette.css — the Tailwind colour palette as CSS
// variables, with a dark-mode remap so legacy classes like `bg-red-50` or
// `text-gray-700` adapt automatically:
//   • 50–300  (tints used as backgrounds/borders) → dark, tinted surfaces
//   • 400–600 (solid accents)                      → unchanged
//   • 700–950 (deep shades used as text)           → light shades
// Run: node scripts/gen-theme-palette.cjs
const fs = require('fs')
const path = require('path')
const colors = require('tailwindcss/colors')

const FAMILIES = ['slate', 'gray', 'zinc', 'neutral', 'stone', 'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan', 'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose']
const NEUTRAL = new Set(['slate', 'gray', 'zinc', 'neutral', 'stone'])
const SHADES = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950']

const hex = h => { h = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)) }
const mix = (a, b, t) => a.map((v, i) => Math.round(v * (1 - t) + b[i] * t))
const trip = rgb => rgb.join(' ')

const DARK_SURFACE = hex('#131a24')
// Neutral ramp for dark mode, aligned with the app's dark surfaces
const DARK_NEUTRAL = {
  50: '#18202c', 100: '#1d2532', 200: '#262f3d', 300: '#344052', 400: '#5f6b7e',
  500: '#7d899c', 600: '#a0aaba', 700: '#c1c8d3', 800: '#dbe0e7', 900: '#eceff4', 950: '#f7f9fb',
}

let light = ''
let dark = ''
for (const f of FAMILIES) {
  const c = colors[f]
  for (const s of SHADES) {
    light += `  --c-${f}-${s}: ${trip(hex(c[s]))};\n`
    let d
    if (NEUTRAL.has(f)) d = hex(DARK_NEUTRAL[s])
    else {
      const base = hex(c[500])
      d = {
        50:  mix(DARK_SURFACE, base, 0.12),
        100: mix(DARK_SURFACE, base, 0.18),
        200: mix(DARK_SURFACE, base, 0.28),
        300: mix(DARK_SURFACE, hex(c[400]), 0.45),
        400: hex(c[400]),
        500: hex(c[500]),
        600: hex(c[500]),
        700: hex(c[300]),
        800: hex(c[200]),
        900: hex(c[100]),
        950: hex(c[50]),
      }[s]
    }
    dark += `  --c-${f}-${s}: ${trip(d)};\n`
  }
}

const out = `/* AUTO-GENERATED by scripts/gen-theme-palette.cjs — do not edit by hand. */
:root {
${light}}
html.dark {
${dark}}
`
fs.writeFileSync(path.join(__dirname, '..', 'src', 'styles', 'palette.css'), out)
console.log('wrote src/styles/palette.css')
